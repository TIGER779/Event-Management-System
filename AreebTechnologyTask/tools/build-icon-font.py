"""
Builds a small Font Awesome icon font that contains only the icons this site uses.

The full Font Awesome solid font is ~157 KB (WOFF2) for ~1,400 icons; this site uses about a dozen,
so the generated font is only a few KB and the browser no longer downloads icons it never shows.

Usage (from the project folder, requires `pip install fonttools`):
    python tools/build-icon-font.py

Run it again whenever you add or change an `fa-...` icon in a view.

Inputs (kept out of wwwroot, so they are not published):
    tools/fontawesome/fa-solid-900.ttf      full Font Awesome 6.5.1 Free solid font
    tools/fontawesome/fontawesome.min.css   full Font Awesome 6.5.1 CSS (icon name -> character map)
Outputs:
    wwwroot/lib/fontawesome/webfonts/fa-solid-subset.woff
    wwwroot/lib/fontawesome/css/icons.css

Font Awesome Free is licensed under CC BY 4.0 (icons), SIL OFL 1.1 (fonts) and MIT (code);
see wwwroot/lib/fontawesome/LICENSE.txt.
"""
import hashlib
import pathlib
import re
import sys

from fontTools import subset

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE_FONT = ROOT / "tools" / "fontawesome" / "fa-solid-900.ttf"
SOURCE_CSS = ROOT / "tools" / "fontawesome" / "fontawesome.min.css"
OUT_FONT = ROOT / "wwwroot" / "lib" / "fontawesome" / "webfonts" / "fa-solid-subset.woff"
OUT_CSS = ROOT / "wwwroot" / "lib" / "fontawesome" / "css" / "icons.css"

# Class names that are styles/modifiers, not icons.
NOT_ICONS = {"solid", "regular", "brands", "classic", "sharp", "fw", "lg", "xs", "sm", "xl", "2x", "3x",
             "spin", "pulse", "border", "pull-left", "pull-right", "solid-900", "solid-subset"}


def used_icon_names():
    """All `fa-<name>` classes used in Razor views and site scripts."""
    names = set()
    for folder, pattern in (("Views", "*.cshtml"), ("wwwroot/js", "*.js")):
        for file in (ROOT / folder).rglob(pattern):
            names.update(re.findall(r"\bfa-([a-z0-9-]+)", file.read_text(encoding="utf-8")))
    return sorted(n for n in names if n not in NOT_ICONS)


def icon_codepoints(names):
    """Map each icon name to its character, using the rules in the full Font Awesome CSS."""
    css = SOURCE_CSS.read_text(encoding="utf-8")
    codes = {}
    # Rules look like: .fa-home:before,.fa-house:before{content:"\f015"}
    for selectors, code in re.findall(r'([^{}]+)\{content:"\\([0-9a-f]+)"\}', css):
        for name in re.findall(r"\.fa-([a-z0-9-]+):before", selectors):
            codes.setdefault(name, int(code, 16))
    missing = [n for n in names if n not in codes]
    if missing:
        sys.exit(f"Unknown Font Awesome icon(s): {', '.join(missing)}")
    return {n: codes[n] for n in names}


def build_font(codepoints):
    options = subset.Options()
    options.flavor = "woff"          # WOFF (zlib) needs no extra packages; every browser supports it
    options.layout_features = ["*"]
    options.name_IDs = ["*"]         # keep the copyright/license names
    options.notdef_outline = True
    font = subset.load_font(str(SOURCE_FONT), options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=sorted(set(codepoints.values())))
    subsetter.subset(font)
    OUT_FONT.parent.mkdir(parents=True, exist_ok=True)
    subset.save_font(font, str(OUT_FONT), options)


def build_css(codepoints):
    version = hashlib.sha256(OUT_FONT.read_bytes()).hexdigest()[:12]
    icon_rules = "\n".join(f'.fa-{name}:before{{content:"\\{code:x}"}}' for name, code in codepoints.items())
    css = f"""/* Generated by tools/build-icon-font.py - do not edit by hand.
   Font Awesome Free 6.5.1 (https://fontawesome.com, License: https://fontawesome.com/license/free),
   reduced to the {len(codepoints)} icons used by this site. */
@font-face{{font-family:"Font Awesome 6 Free";font-style:normal;font-weight:900;font-display:swap;src:url(../webfonts/fa-solid-subset.woff?v={version}) format("woff")}}
.fa,.fas,.fa-solid{{-moz-osx-font-smoothing:grayscale;-webkit-font-smoothing:antialiased;display:var(--fa-display,inline-block);font-style:normal;font-variant:normal;line-height:1;text-rendering:auto;font-family:"Font Awesome 6 Free";font-weight:900}}
.fa-fw{{text-align:center;width:1.25em}}
{icon_rules}
"""
    OUT_CSS.parent.mkdir(parents=True, exist_ok=True)
    OUT_CSS.write_text(css, encoding="utf-8", newline="\n")


def main():
    names = used_icon_names()
    codepoints = icon_codepoints(names)
    build_font(codepoints)
    build_css(codepoints)
    print(f"{len(codepoints)} icons: {', '.join(codepoints)}")
    print(f"{OUT_FONT.relative_to(ROOT)}: {OUT_FONT.stat().st_size:,} bytes")
    print(f"{OUT_CSS.relative_to(ROOT)}: {OUT_CSS.stat().st_size:,} bytes")


if __name__ == "__main__":
    main()
